# ============================================================
# 【整体思路】
# 经典 DP 题。用二维数组 dp[i][j] 表示 text1 前 i 个字符
# 与 text2 前 j 个字符的 LCS 长度。
# 若 text1[i-1] == text2[j-1]，则 dp[i][j] = dp[i-1][j-1] + 1
# 否则 dp[i][j] = max(dp[i-1][j], dp[i][j-1])
# 时间复杂度 O(m*n)，空间复杂度 O(m*n)
# ============================================================

def lcs(text1, text2):
    m, n = len(text1), len(text2)

    # dp[i][j] = text1[:i] 和 text2[:j] 的 LCS 长度
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if text1[i-1] == text2[j-1]:
                # 当前字符匹配，LCS 长度 +1
                dp[i][j] = dp[i-1][j-1] + 1
            else:
                # 当前字符不匹配，取两个方向的最大值
                dp[i][j] = max(dp[i-1][j], dp[i][j-1])

    # 右下角即为最终答案
    return dp[m][n]


# ============================================================
# 手动测试用例
# ============================================================
print(lcs("abcde", "ace"))   # 期望：3（"ace"）
print(lcs("abc", "def"))     # 期望：0（无公共子序列）
print(lcs("abc", "abc"))     # 期望：3（完全相同）
print(lcs("", "abc"))        # 期望：0（空字符串边界）


# ============================================================
# 时空复杂度
# ============================================================
# 时间：O(m*n) — 两层循环遍历所有字符对
# 空间：O(m*n) — 二维 dp 表；可压缩到 O(n) 用滚动数组